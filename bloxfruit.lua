-- Vòng lặp quét UI (Chỉ xử lý text và xóa Arvyn, không thay đổi ảnh nữa)
task.spawn(function()
    while task.wait(0.15) do
        pcall(function()
            local coreGui = game:GetService("CoreGui")
            local players = game:GetService("Players")
            local localPlayer = players.LocalPlayer
            local containers = { coreGui, localPlayer:FindFirstChild("PlayerGui") }

            for _, container in ipairs(containers) do
                if container then
                    for _, obj in ipairs(container:GetDescendants()) do
                        if obj:IsA("TextLabel") or obj:IsA("TextButton") or obj:IsA("TextBox") then
                            local text = obj.Text
                            if text and text ~= "" then
                                if text:find("Arvyn") then
                                    obj.Text = text:gsub("Arvyn Scripts", "NiceXbloxfruit"):gsub("Arvyn", "NiceXbloxfruit")
                                end

                                for eng, vie in pairs(translations) do
                                    if text == eng or text:lower() == eng:lower() then
                                        obj.Text = vie
                                    end
                                end
                            end
                        end
                    end
                end
            end
        end)
    end
end)
